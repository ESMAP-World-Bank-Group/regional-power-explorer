const RELIABILITY_META = {
  high:   { color: '#1A9060', label: 'good coverage' },
  medium: { color: '#B87820', label: 'medium coverage' },
  low:    { color: '#B84040', label: 'sparse coverage' },
};
const level = pct => (pct >= 90 ? 'high' : pct >= 70 ? 'medium' : 'low');

// Prefer measured country coverage; fall back to the region aggregate.
export function sourceReliability(regionId, source, iso) {
  let pct = iso ? COUNTRY_COVERAGE[iso]?.[source] : undefined;
  if (pct == null) pct = REGION_COVERAGE[regionId]?.[source];
  if (pct == null) return null;
  const m = RELIABILITY_META[level(pct)];
  return { color: m.color, label: m.label, pct: Math.min(pct, 100) };
}
